"""phase 5 checkout and orders schema

Revision ID: 0008
Revises: 0007
Create Date: 2026-09-27

Creates the five checkout tables - addresses, tax_rates, shipping_rules,
orders, order_items - and pays off one constraint deferred from Phase 4.

Five details are load-bearing:

* ``uq_orders_cart_id`` is the idempotency guarantee, not a tidiness rule.
  One cart produces exactly one order, so a double-submitted checkout
  cannot buy the same basket twice; the service catches this constraint and
  returns the order that won.
* ``ck_orders_totals_reconcile`` and the two ``ck_order_items_line_*``
  checks put the money arithmetic where a service bug cannot bypass it.
* ``order_items.variant_id`` and ``orders.user_id``/``cart_id`` are
  RESTRICT. A variant that has been sold, a customer who has ordered and
  the cart holding an order's reservations all become undeletable, which is
  what keeps order history readable and the reservations reachable.
* ``orders.shipping_address`` and ``billing_address`` are JSONB snapshots
  with **no foreign key** to ``addresses``. Editing or deleting a saved
  address must never rewrite where a past order was sent.
* the two partial unique indexes - one default address per user, one active
  tax rate per jurisdiction - follow the same shape as the catalogue's
  one-primary-image index and the cart's one-ACTIVE-cart index.

The ride-along: ``uq_inventory_adjustments_transaction_id``. Phase 4 listed
the columns without it and deferred the constraint to "Phase 5's first
migration" rather than creating an 0008 of its own for one line. An
adjustment is the human half of exactly one ledger entry, so two
adjustments claiming the same transaction would make "who changed this
stock, and why" ambiguous.

There is no data backfill: there are no orders to migrate. The new
permission codes are seeded separately in 0009, keeping schema and data
changes independent as 0002/0003, 0004/0005 and 0006/0007 already do.
"""
